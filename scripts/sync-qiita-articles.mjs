import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, join, resolve } from 'node:path';
import matter from 'gray-matter';

const projectRoot = process.cwd();
const generatedDirectory = join(projectRoot, 'lib', 'generated');
const generatedFile = join(generatedDirectory, 'qiita-articles.ts');
const defaultRepository =
  'https://github.com/Morishita-mm/QiitaArticle.git';
const articleIdPattern = /^[0-9a-f]{20}$/i;

let temporaryDirectory;

function runGit(args) {
  execFileSync('git', args, { stdio: 'inherit' });
}

function normalizeArticlesDirectory(candidate) {
  const absoluteCandidate = resolve(candidate);
  const publicDirectory = join(absoluteCandidate, 'public');

  try {
    if (statSync(publicDirectory).isDirectory()) {
      return publicDirectory;
    }
  } catch {
    // The configured path may already point at public/.
  }

  try {
    if (statSync(absoluteCandidate).isDirectory()) {
      return absoluteCandidate;
    }
  } catch {
    // A clear error is thrown below.
  }

  throw new Error(
    `Qiita articles directory was not found: ${absoluteCandidate}`,
  );
}

function cloneArticlesRepository() {
  temporaryDirectory = mkdtempSync(join(tmpdir(), 'morimizu-qiita-'));
  const checkoutDirectory = join(temporaryDirectory, 'repository');
  const repository =
    process.env.QIITA_ARTICLES_REPOSITORY?.trim() || defaultRepository;
  const ref = process.env.QIITA_ARTICLES_REF?.trim();

  if (ref) {
    runGit([
      'clone',
      '--filter=blob:none',
      '--no-checkout',
      repository,
      checkoutDirectory,
    ]);
    runGit([
      '-C',
      checkoutDirectory,
      'fetch',
      '--depth',
      '1',
      'origin',
      ref,
    ]);
    runGit(['-C', checkoutDirectory, 'checkout', '--detach', 'FETCH_HEAD']);
  } else {
    runGit(['clone', '--depth', '1', repository, checkoutDirectory]);
  }

  return join(checkoutDirectory, 'public');
}

function resolveArticlesDirectory() {
  const configuredDirectory = process.env.QIITA_ARTICLES_DIR?.trim();
  return configuredDirectory
    ? normalizeArticlesDirectory(configuredDirectory)
    : cloneArticlesRepository();
}

function isPublicArticle(data) {
  return (
    typeof data.id === 'string' &&
    articleIdPattern.test(data.id) &&
    data.private === false &&
    data.ignorePublish === false
  );
}

function createGeneratedSource(articles) {
  return `// This file is generated by scripts/sync-qiita-articles.mjs.\n` +
    `// Edit articles in the QiitaArticle repository, not here.\n\n` +
    `export const generatedQiitaArticles = ${JSON.stringify(articles, null, 2)} as const;\n`;
}

try {
  const articlesDirectory = resolveArticlesDirectory();
  const markdownFiles = readdirSync(articlesDirectory)
    .filter((fileName) => fileName.endsWith('.md'))
    .sort((left, right) => left.localeCompare(right, 'ja'));

  const excluded = {
    unpublished: 0,
    private: 0,
    ignored: 0,
    invalid: 0,
  };
  const articles = [];

  for (const fileName of markdownFiles) {
    const source = readFileSync(join(articlesDirectory, fileName), 'utf8');
    const { data, content } = matter(source);

    if (data.private === true) {
      excluded.private += 1;
      continue;
    }
    if (data.ignorePublish === true) {
      excluded.ignored += 1;
      continue;
    }
    if (data.id === null || data.id === undefined || data.id === '') {
      excluded.unpublished += 1;
      continue;
    }
    if (!isPublicArticle(data) || typeof data.title !== 'string') {
      excluded.invalid += 1;
      continue;
    }

    articles.push({
      id: data.id,
      title: data.title.trim(),
      tags: Array.isArray(data.tags)
        ? data.tags.filter((tag) => typeof tag === 'string' && tag.trim())
        : [],
      updatedAt:
        typeof data.updated_at === 'string' ? data.updated_at.trim() : '',
      content: content.trim(),
      sourceFile: basename(fileName),
    });
  }

  if (articles.length === 0) {
    throw new Error(
      'No public Qiita articles were found. Refusing to generate an empty site.',
    );
  }

  articles.sort((left, right) =>
    right.updatedAt.localeCompare(left.updatedAt),
  );

  mkdirSync(generatedDirectory, { recursive: true });
  writeFileSync(generatedFile, createGeneratedSource(articles), 'utf8');

  console.log(
    `Synced ${articles.length} public articles from ${articlesDirectory}. ` +
      `Excluded ${excluded.unpublished} unpublished, ${excluded.private} private, ` +
      `${excluded.ignored} ignored, and ${excluded.invalid} invalid articles.`,
  );
} finally {
  if (temporaryDirectory) {
    rmSync(temporaryDirectory, { recursive: true, force: true });
  }
}
